#!/usr/bin/env python3
"""Generates themed widget / notification layouts and drawables (light, dark, auto = follows system)."""
import os
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'res')
THEMES = {
    'dark':  dict(bg='#E615171C', text='#FFE6E8EC', muted='#FF9097A3', track='#FF3A3E47', pct='#FFFFFFFF'),
    'light': dict(bg='#F2FFFFFF', text='#FF1D1F24', muted='#FF6B7280', track='#FFDDE1E8', pct='#FF1D1F24'),
}
COLORS = dict(blue='388BFD', green='51A34F', amber='E6A028', red='DC3C3C', grey='8A909B')
NS = 'xmlns:android="http://schemas.android.com/apk/res/android"'

def write(path, s):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w') as f: f.write('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/gen_layouts.py -->\n' + s)

def bars(t, height, pct):
    out = ''
    for c in COLORS:
        out += f'''        <ProgressBar android:id="@+id/bar_{c}" style="@android:style/Widget.ProgressBar.Horizontal"
            android:layout_width="match_parent" android:layout_height="match_parent"
            android:max="100" android:progressDrawable="@drawable/progress_{c}_{t}" android:visibility="gone" />
'''
    if pct:
        out += f'''        <TextView android:id="@+id/pct" android:layout_width="match_parent" android:layout_height="match_parent"
            android:gravity="center" android:textColor="{THEMES[t]['pct']}" android:textSize="10sp" android:textStyle="bold" />
'''
    return f'''    <FrameLayout android:layout_width="match_parent" android:layout_height="{height}" android:layout_marginTop="{'4dp' if pct else '3dp'}">
{out}    </FrameLayout>
'''

def row(t):  # one printer, full details (widget + expanded notification)
    p = THEMES[t]
    return f'''<LinearLayout {NS}
    android:layout_width="match_parent" android:layout_height="wrap_content"
    android:orientation="vertical" android:paddingTop="8dp">
    <LinearLayout android:layout_width="match_parent" android:layout_height="wrap_content" android:orientation="horizontal">
        <TextView android:id="@+id/dot" android:layout_width="wrap_content" android:layout_height="wrap_content"
            android:layout_marginRight="5dp" android:text="\\u25CF" android:textSize="11sp" />
        <TextView android:id="@+id/name" android:layout_width="wrap_content" android:layout_height="wrap_content"
            android:singleLine="true" android:ellipsize="end" android:textColor="{p['text']}" android:textSize="13sp" android:textStyle="bold" />
        <TextView android:id="@+id/model" android:layout_width="0dp" android:layout_height="wrap_content" android:layout_weight="1"
            android:layout_marginLeft="6dp" android:singleLine="true" android:ellipsize="end" android:textColor="{p['muted']}" android:textSize="11sp" />
        <TextView android:id="@+id/label" android:layout_width="wrap_content" android:layout_height="wrap_content"
            android:layout_marginLeft="8dp" android:textSize="12sp" android:textStyle="bold" />
    </LinearLayout>
    <TextView android:id="@+id/file" android:layout_width="match_parent" android:layout_height="wrap_content"
        android:layout_marginLeft="16dp" android:singleLine="true" android:ellipsize="end"
        android:textColor="{p['muted']}" android:textSize="12sp" android:visibility="gone" />
{bars(t, '14dp', True)}    <TextView android:id="@+id/meta" android:layout_width="match_parent" android:layout_height="wrap_content"
        android:layout_marginTop="3dp" android:textColor="{p['muted']}" android:textSize="11sp" android:visibility="gone" />
</LinearLayout>
'''

def col(t):  # one printer as a compact column (collapsed notification)
    p = THEMES[t]
    return f'''<LinearLayout {NS}
    android:layout_width="0dp" android:layout_height="wrap_content" android:layout_weight="1"
    android:layout_marginRight="10dp" android:orientation="vertical">
    <LinearLayout android:layout_width="match_parent" android:layout_height="wrap_content" android:orientation="horizontal">
        <TextView android:id="@+id/name" android:layout_width="0dp" android:layout_height="wrap_content" android:layout_weight="1"
            android:singleLine="true" android:ellipsize="end" android:textColor="{p['text']}" android:textSize="12sp" android:textStyle="bold" />
        <TextView android:id="@+id/label" android:layout_width="wrap_content" android:layout_height="wrap_content"
            android:layout_marginLeft="4dp" android:singleLine="true" android:textSize="12sp" />
    </LinearLayout>
{bars(t, '6dp', False)}</LinearLayout>
'''

def widget(t):
    p = THEMES[t]
    return f'''<LinearLayout {NS}
    android:id="@+id/root" android:layout_width="match_parent" android:layout_height="match_parent"
    android:orientation="vertical" android:padding="10dp" android:background="@drawable/widget_bg_{t}">
    <LinearLayout android:id="@+id/header" android:layout_width="match_parent" android:layout_height="wrap_content"
        android:orientation="horizontal" android:gravity="center_vertical">
        <TextView android:layout_width="0dp" android:layout_height="wrap_content" android:layout_weight="1"
            android:text="Printers" android:textColor="{p['text']}" android:textSize="13sp" android:textStyle="bold" />
        <TextView android:id="@+id/updated" android:layout_width="wrap_content" android:layout_height="wrap_content"
            android:textColor="{p['muted']}" android:textSize="11sp" />
    </LinearLayout>
    <LinearLayout android:id="@+id/rows" android:layout_width="match_parent" android:layout_height="wrap_content" android:orientation="vertical" />
    <TextView android:id="@+id/message" android:layout_width="match_parent" android:layout_height="wrap_content"
        android:layout_marginTop="6dp" android:textColor="{p['muted']}" android:textSize="12sp" android:visibility="gone" />
</LinearLayout>
'''

def notif_small():
    return f'''<LinearLayout {NS} android:id="@+id/cols"
    android:layout_width="match_parent" android:layout_height="wrap_content" android:orientation="horizontal" />
'''

def notif_big():
    return f'''<LinearLayout {NS} android:id="@+id/rows"
    android:layout_width="match_parent" android:layout_height="wrap_content" android:orientation="vertical" />
'''

for t, p in THEMES.items():
    for c, h in COLORS.items():
        write(f'{ROOT}/drawable/progress_{c}_{t}.xml', f'''<layer-list {NS}>
    <item android:id="@android:id/background"><shape><corners android:radius="4dp" /><solid android:color="{p['track']}" /></shape></item>
    <item android:id="@android:id/progress"><clip><shape><corners android:radius="4dp" /><solid android:color="#FF{h}" /></shape></clip></item>
</layer-list>
''')
    write(f'{ROOT}/drawable/widget_bg_{t}.xml', f'''<shape {NS}>
    <corners android:radius="16dp" />
    <solid android:color="{p['bg']}" />
</shape>
''')
    for name, fn in (('widget', widget), ('row', row), ('col', col)):
        write(f'{ROOT}/layout/{name}_{t}.xml', fn(t))
# "auto" variants follow the system theme through the -night resource qualifier
for name, fn in (('widget', widget), ('row', row), ('col', col)):
    write(f'{ROOT}/layout/{name}_auto.xml', fn('light'))
    write(f'{ROOT}/layout-night/{name}_auto.xml', fn('dark'))
write(f'{ROOT}/layout/notif_small.xml', notif_small())
write(f'{ROOT}/layout/notif_big.xml', notif_big())
print('ok')
